//! Envelope encryption primitives.
//!
//! In Phases 0–2 this module wraps pgcrypto under a narrow API. In
//! Phase 3, the same API switches to talk to Vault's transit engine
//! (see ADR-0007). Call sites do not need to change.
//!
//! # Guarantees
//!
//! - Plaintext exists in Rust memory only inside a single method call,
//!   and only wrapped in a [`SecretString`] whose `Debug` impl redacts
//!   the contents.
//! - The KEK is loaded once at startup from `KUBINATE__KEK` and is held
//!   in a [`SecretString`] for the lifetime of the [`PgcryptoStore`];
//!   it is never serialized or logged.
//! - Every insert/read/delete opens a tenant-scoped transaction that
//!   issues `SET LOCAL app.current_tenant_id`, so RLS on the `secrets`
//!   table enforces cross-tenant isolation even if a caller passes in
//!   the wrong organization.

use async_trait::async_trait;
use base64::{engine::general_purpose::STANDARD as B64, Engine};
use secrecy::{ExposeSecret, SecretString};
use sqlx::PgPool;
use thiserror::Error;
use uuid::Uuid;

use crate::metrics::names::SECRET_STORE_DISPATCH_TOTAL;

/// A handle to a secret whose ciphertext lives in the database.
///
/// The handle is cheap to `Clone` / `Copy` and safe to log — it carries
/// only identifiers, never key material. The `organization_id` is part
/// of the handle so that the store can scope the lookup transaction
/// correctly without requiring a separate parameter on every call.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SecretRef {
    /// Primary key of the `secrets` row.
    pub id: Uuid,
    /// Owning tenant. Must match the `app.current_tenant_id` of any
    /// transaction that reads the row, or RLS will reject the lookup.
    pub organization_id: Uuid,
}

/// Errors raised by the secrets subsystem.
#[derive(Debug, Error)]
pub enum SecretError {
    /// The secret could not be found (or was hidden by RLS).
    #[error("secret not found: {0}")]
    NotFound(Uuid),
    /// Decryption failed — usually a KEK mismatch or tampered ciphertext.
    #[error("decryption failed")]
    Decrypt,
    /// The configured KEK / `AppRole` token failed validation at
    /// construction time. Operator action: check the env var.
    #[error("invalid KEK: {0}")]
    InvalidKek(String),
    /// The remote secret backend rejected our credential. Distinct
    /// from [`Self::InvalidKek`] so on-call can tell "rotate the
    /// `AppRole` secret-id" (this) apart from "fix the env var"
    /// (`InvalidKek`). Vault 401 (token expired/revoked), 403 (policy
    /// denial), and 404 on encrypt/decrypt (key not found) all map
    /// here. The string is the HTTP status only — bodies are
    /// scrubbed before they reach this variant to keep tracing logs
    /// from echoing key paths or error fragments.
    #[error("backend auth failed: {0}")]
    AuthFailed(String),
    /// Underlying database failure.
    #[error(transparent)]
    Database(#[from] sqlx::Error),
}

/// Abstract secret store. Implementations: [`PgcryptoStore`] (phases 0–2),
/// `VaultStore` (phase 3+ — see ADR-0007).
#[async_trait]
pub trait SecretStore: Send + Sync {
    /// Encrypt a plaintext and return a handle scoped to `organization_id`.
    async fn put(
        &self,
        organization_id: Uuid,
        plaintext: SecretString,
    ) -> Result<SecretRef, SecretError>;

    /// Resolve a handle back to plaintext.
    ///
    /// Callers must drop the returned [`SecretString`] as soon as the
    /// plaintext is no longer needed. The `integrations::hetzner`
    /// client, for example, resolves and forgets the token within a
    /// single HTTP call (ADR-0007, threat-model Flow 2).
    async fn get(&self, handle: &SecretRef) -> Result<SecretString, SecretError>;

    /// Zero the ciphertext in place and delete the row.
    async fn delete(&self, handle: &SecretRef) -> Result<(), SecretError>;
}

/// pgcrypto-backed [`SecretStore`].
///
/// Uses two layers of `pgp_sym_encrypt` to realise envelope encryption:
/// a per-row DEK is generated by `gen_random_bytes` inside a single
/// SQL statement, encrypts the plaintext, and is itself encrypted under
/// the application-wide KEK before being stored alongside the ciphertext.
pub struct PgcryptoStore {
    pool: PgPool,
    kek: SecretString,
}

impl PgcryptoStore {
    /// Build a store with an explicit base64-encoded 32-byte KEK.
    ///
    /// # Errors
    /// Returns [`SecretError::InvalidKek`] if the KEK is not valid
    /// base64 or does not decode to exactly 32 bytes.
    pub fn new(pool: PgPool, kek: SecretString) -> Result<Self, SecretError> {
        let decoded = B64
            .decode(kek.expose_secret().as_bytes())
            .map_err(|e| SecretError::InvalidKek(format!("not valid base64: {e}")))?;
        if decoded.len() != 32 {
            return Err(SecretError::InvalidKek(format!(
                "expected 32 bytes, got {}",
                decoded.len()
            )));
        }
        Ok(Self { pool, kek })
    }

    /// Build a store using the KEK loaded from `KUBINATE__KEK`.
    ///
    /// # Errors
    /// Returns [`SecretError::InvalidKek`] if the env var is unset or
    /// fails the validation rules documented on [`Self::new`].
    pub fn from_env(pool: PgPool) -> Result<Self, SecretError> {
        let kek = std::env::var("KUBINATE__KEK")
            .map_err(|_| SecretError::InvalidKek("KUBINATE__KEK not set".to_string()))?;
        Self::new(pool, SecretString::from(kek))
    }
}

#[async_trait]
impl SecretStore for PgcryptoStore {
    async fn put(
        &self,
        organization_id: Uuid,
        plaintext: SecretString,
    ) -> Result<SecretRef, SecretError> {
        metrics::counter!(SECRET_STORE_DISPATCH_TOTAL, "backend" => "pgcrypto", "op" => "put")
            .increment(1);
        let id = Uuid::now_v7();

        let mut tx = self.pool.begin().await?;
        sqlx::query(&set_local_tenant(organization_id))
            .execute(&mut *tx)
            .await?;

        // `WITH ... AS MATERIALIZED` forces the DEK to be generated once
        // and reused on both sides of the envelope. Without MATERIALIZED
        // the planner is free to inline the CTE and evaluate it twice.
        sqlx::query(
            r"
            WITH dek_raw AS MATERIALIZED (
                SELECT gen_random_bytes(32) AS raw
            )
            INSERT INTO secrets (id, organization_id, ciphertext, wrapped_dek)
            SELECT
                $1,
                $2,
                pgp_sym_encrypt($3, encode(dek.raw, 'base64')),
                pgp_sym_encrypt(encode(dek.raw, 'base64'), $4)
            FROM dek_raw dek
            ",
        )
        .bind(id)
        .bind(organization_id)
        .bind(plaintext.expose_secret())
        .bind(self.kek.expose_secret())
        .execute(&mut *tx)
        .await?;

        tx.commit().await?;

        tracing::debug!(secret_id = %id, org = %organization_id, "secret stored");
        Ok(SecretRef {
            id,
            organization_id,
        })
    }

    async fn get(&self, handle: &SecretRef) -> Result<SecretString, SecretError> {
        metrics::counter!(SECRET_STORE_DISPATCH_TOTAL, "backend" => "pgcrypto", "op" => "get")
            .increment(1);
        let mut tx = self.pool.begin().await?;
        sqlx::query(&set_local_tenant(handle.organization_id))
            .execute(&mut *tx)
            .await?;

        let row: Option<(String,)> = sqlx::query_as(
            r"
            SELECT pgp_sym_decrypt(
                       ciphertext,
                       pgp_sym_decrypt(wrapped_dek, $2)
                   )
            FROM secrets
            WHERE id = $1
            ",
        )
        .bind(handle.id)
        .bind(self.kek.expose_secret())
        .fetch_optional(&mut *tx)
        .await
        .map_err(decrypt_or_db)?;

        tx.commit().await?;

        match row {
            Some((plaintext,)) => Ok(SecretString::from(plaintext)),
            None => Err(SecretError::NotFound(handle.id)),
        }
    }

    async fn delete(&self, handle: &SecretRef) -> Result<(), SecretError> {
        metrics::counter!(SECRET_STORE_DISPATCH_TOTAL, "backend" => "pgcrypto", "op" => "delete")
            .increment(1);
        let mut tx = self.pool.begin().await?;
        sqlx::query(&set_local_tenant(handle.organization_id))
            .execute(&mut *tx)
            .await?;

        // Overwrite ciphertext + wrapped DEK before the delete. Postgres
        // MVCC leaves dead tuples on disk until VACUUM, so this is not
        // cryptographic erasure — true crypto-shredding is a Vault/KMS
        // property we pick up in Phase 3. This is still defence-in-depth:
        // anything reading the current row version sees no key material.
        sqlx::query(
            "UPDATE secrets SET ciphertext = ''::bytea, wrapped_dek = ''::bytea WHERE id = $1",
        )
        .bind(handle.id)
        .execute(&mut *tx)
        .await?;

        sqlx::query("DELETE FROM secrets WHERE id = $1")
            .bind(handle.id)
            .execute(&mut *tx)
            .await?;

        tx.commit().await?;
        Ok(())
    }
}

/// Build a `SET LOCAL` statement for the tenant discriminator.
///
/// Postgres's `SET` command does not accept bind parameters, so the
/// UUID has to be interpolated. [`Uuid::Display`] emits hex + dashes
/// only, which cannot produce SQL injection.
fn set_local_tenant(organization_id: Uuid) -> String {
    format!("SET LOCAL app.current_tenant_id = '{organization_id}'")
}

fn decrypt_or_db(err: sqlx::Error) -> SecretError {
    // pgcrypto surfaces bad KEK / tampered ciphertext as a database
    // error with a recognisable message. Everything else is bubbled up
    // as-is so that the surrounding context can handle it.
    let text = err.to_string().to_ascii_lowercase();
    if text.contains("wrong key") || text.contains("corrupt data") {
        SecretError::Decrypt
    } else {
        SecretError::Database(err)
    }
}

