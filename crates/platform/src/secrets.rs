    fn new_rejects_kek_that_is_not_base64() {
        // We can't easily construct a PgcryptoStore without a pool, but
        // we can exercise the KEK-decoding branch via the base64 crate
        // directly to guarantee the error shape stays stable.
        let bad = SecretString::from("not!!!valid!!!base64".to_string());
        let err = B64.decode(bad.expose_secret().as_bytes()).unwrap_err();
        assert!(format!("{err}").to_lowercase().contains("invalid"));
    }
