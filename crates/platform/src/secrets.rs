// Sprint 4 ticket 02 — Vault transit-engine SecretStore.
//
// The `VaultStore` is a drop-in replacement for `PgcryptoStore` behind
// the `SecretStore` trait. The pgcrypto path stays compiled in; the
// API binary picks one at startup via the `KUBINATE__SECRETS_BACKEND`
// env var. Migration tooling that re-keys existing rows is out of
// scope for this chunk — see `docs/backlog/sprint-4/02-vault-migration.md`
// "Sprint 4 partial scope" for the full path.
//
// Design:
//
// - The `secrets` table layout is unchanged. Vault rows write
//   `algorithm = 'vault_transit_v1'`; pgcrypto rows continue to
//   write the default `'pgp_sym_v1'`. The `algorithm` column is the
//   discriminator a future migration binary reads to know which
//   backend originally encrypted a row.
// - The `wrapped_dek` column is empty for Vault rows — Vault's
//   transit engine manages the DEK lifecycle internally; we never
//   see one. The column stays NOT NULL by storing an empty BYTEA
//   so the schema can carry both backends without a migration.
// - The HTTP client to a real Vault is **not** in this chunk. The
//   `VaultTransit` trait is the seam; an `HttpVaultTransit` impl
//   lands once a real Vault deploy exists for it to hit (Sprint
//   5+). The `InMemoryVaultTransit` test impl exercises the full
//   `SecretStore` contract against `VaultStore` so the trait-level
//   parity property is verified in CI today.
// ===========================================================================

/// Algorithm tag for Vault-encrypted rows in the `secrets` table.
/// Pinned as a constant so a typo in either the writer or the
/// reader fails loudly rather than silently writing rows the other
/// backend can't decrypt.
pub const VAULT_ALGORITHM_TAG: &str = "vault_transit_v1";

/// Per-org Vault key naming. `kubinate/<organization_id>` keeps
/// transit keys isolated per tenant; a leaked key compromises one
/// org, not the fleet. The `kubinate/` prefix matches the
/// `KUBINATE__VAULT_KEY_PREFIX` env var the future
/// `HttpVaultTransit` reads (default `kubinate`).
fn vault_key_name(prefix: &str, organization_id: Uuid) -> String {
    format!("{prefix}/{organization_id}")
}

/// Abstraction over the Vault transit engine. Production uses a
/// reqwest-backed HTTP impl (Sprint 5+); tests use
/// [`InMemoryVaultTransit`].
///
/// Operations map 1:1 with Vault transit endpoints:
/// - [`Self::ensure_key`] — `POST /v1/transit/keys/<name>` (idempotent).
/// - [`Self::encrypt`] — `POST /v1/transit/encrypt/<name>`.
/// - [`Self::decrypt`] — `POST /v1/transit/decrypt/<name>`.
#[async_trait]
pub trait VaultTransit: Send + Sync {
    /// Ensure the named transit key exists. Vault returns 204 on
    /// create and 204 on a no-op re-create; both are success.
    async fn ensure_key(&self, key_name: &str) -> Result<(), SecretError>;

    /// Encrypt plaintext under the named key. Returns the
    /// `vault:vN:...` envelope string Vault hands back.
    async fn encrypt(&self, key_name: &str, plaintext: &str) -> Result<String, SecretError>;

    /// Decrypt a `vault:vN:...` envelope back to plaintext.
    async fn decrypt(&self, key_name: &str, ciphertext: &str) -> Result<String, SecretError>;
}

/// In-memory [`VaultTransit`] for tests. Keys + plaintext live in a
/// `Mutex<HashMap>`; ciphertext is a deterministic synthetic string
/// `vault:test:<uuid>` whose suffix indexes back into the map. No
/// real cryptography — the production HTTP impl carries that.
///
/// Why deterministic ciphertext: the parity tests (see
/// `crates/platform/tests/secrets.rs`) need to assert that a
/// re-read of a `secrets` row produces the same plaintext, which
/// requires that the ciphertext written under a particular `put`
/// resolves stably under a later `get`. A random-per-encrypt
/// fake would still satisfy the contract via the `HashMap`, but
/// debugging a failing parity test is easier when the ciphertext
/// looks like the row id.
pub struct InMemoryVaultTransit {
    inner: std::sync::Mutex<InMemoryVault>,
}

#[derive(Default)]
struct InMemoryVault {
    /// `key_name -> exists`.
    keys: std::collections::HashSet<String>,
    /// `(key_name, ciphertext) -> plaintext`.
    ciphertexts: std::collections::HashMap<(String, String), String>,
    /// Monotonic counter for synthetic ciphertext ids.
    counter: u64,
}

impl InMemoryVaultTransit {
    /// Build an empty in-memory transit fake.
    #[must_use]
    pub fn new() -> Self {
        Self {
            inner: std::sync::Mutex::new(InMemoryVault::default()),
        }
    }
}

impl Default for InMemoryVaultTransit {
    fn default() -> Self {
        Self::new()
    }
}

#[async_trait]
impl VaultTransit for InMemoryVaultTransit {
    async fn ensure_key(&self, key_name: &str) -> Result<(), SecretError> {
        let mut g = self.inner.lock().expect("vault transit fake poisoned");
        g.keys.insert(key_name.to_string());
        Ok(())
    }

    async fn encrypt(&self, key_name: &str, plaintext: &str) -> Result<String, SecretError> {
        let mut g = self.inner.lock().expect("vault transit fake poisoned");
        if !g.keys.contains(key_name) {
            return Err(SecretError::InvalidKek(format!(
                "no transit key named '{key_name}'"
            )));
        }
        g.counter += 1;
        let ciphertext = format!("vault:test:{:016x}", g.counter);
        g.ciphertexts.insert(
            (key_name.to_string(), ciphertext.clone()),
            plaintext.to_string(),
        );
        Ok(ciphertext)
    }

    async fn decrypt(&self, key_name: &str, ciphertext: &str) -> Result<String, SecretError> {
        let g = self.inner.lock().expect("vault transit fake poisoned");
        if !g.keys.contains(key_name) {
            return Err(SecretError::InvalidKek(format!(
                "no transit key named '{key_name}'"
            )));
        }
        g.ciphertexts
            .get(&(key_name.to_string(), ciphertext.to_string()))
            .cloned()
            .ok_or(SecretError::Decrypt)
    }
}

/// Vault-transit-backed [`SecretStore`].
///
/// The shape is:
///
/// 1. `put` — generate a synthetic per-org Vault key name, ensure
///    it exists in Vault, encrypt the plaintext, persist the
///    ciphertext + algorithm tag in the `secrets` table.
/// 2. `get` — load the row, send the ciphertext back to Vault
///    decrypt, return the plaintext.
/// 3. `delete` — same blank-and-DELETE shape as `PgcryptoStore`.
///
/// The `key_prefix` segment of the Vault key name is configurable
/// so different deploys (staging / production) can share a Vault
/// instance without colliding.
pub struct VaultStore<T: VaultTransit> {
    pool: PgPool,
    transit: T,
    key_prefix: String,
}

impl<T: VaultTransit> VaultStore<T> {
    /// Build a [`VaultStore`] from a pool, a transit client, and
    /// the per-deploy key-name prefix. The prefix is intended to
    /// be loaded from `KUBINATE__VAULT_KEY_PREFIX` (default
    /// `kubinate`) — wiring lives at the API edge, not here.
    #[must_use]
    pub fn new(pool: PgPool, transit: T, key_prefix: impl Into<String>) -> Self {
        Self {
            pool,
            transit,
            key_prefix: key_prefix.into(),
        }
    }
}

#[async_trait]
impl<T: VaultTransit> SecretStore for VaultStore<T> {
    async fn put(
        &self,
        organization_id: Uuid,
        plaintext: SecretString,
    ) -> Result<SecretRef, SecretError> {
        metrics::counter!(SECRET_STORE_DISPATCH_TOTAL, "backend" => "vault", "op" => "put")
            .increment(1);
        let key_name = vault_key_name(&self.key_prefix, organization_id);

        // Lazy key creation — idempotent on the Vault side. We
        // could move this out to a startup-time "ensure all org
        // keys exist" pass, but that doesn't compose with the
        // multi-tenant lifecycle (orgs come and go); per-`put`
        // ensure_key is the simplest correct shape.
        self.transit.ensure_key(&key_name).await?;
        let ciphertext_str = self
            .transit
            .encrypt(&key_name, plaintext.expose_secret())
            .await?;

        let id = Uuid::now_v7();
        let mut tx = self.pool.begin().await?;
        sqlx::query(&set_local_tenant(organization_id))
            .execute(&mut *tx)
            .await?;
        sqlx::query(
            r"
            INSERT INTO secrets (id, organization_id, ciphertext, wrapped_dek, algorithm)
            VALUES ($1, $2, $3, $4, $5)
            ",
        )
        .bind(id)
        .bind(organization_id)
        .bind(ciphertext_str.as_bytes())
        // Vault-managed keys: no per-row DEK to wrap. The column is
        // NOT NULL so we store an empty BYTEA; readers must consult
        // `algorithm` before treating `wrapped_dek` as meaningful.
        .bind::<&[u8]>(b"")
        .bind(VAULT_ALGORITHM_TAG)
        .execute(&mut *tx)
        .await?;

        tx.commit().await?;
        tracing::debug!(
            secret_id = %id,
            org = %organization_id,
            backend = "vault",
            "secret stored"
        );
        Ok(SecretRef {
            id,
            organization_id,
        })
    }

    async fn get(&self, handle: &SecretRef) -> Result<SecretString, SecretError> {
        metrics::counter!(SECRET_STORE_DISPATCH_TOTAL, "backend" => "vault", "op" => "get")
            .increment(1);
        let mut tx = self.pool.begin().await?;
        sqlx::query(&set_local_tenant(handle.organization_id))
            .execute(&mut *tx)
            .await?;

        let row: Option<(Vec<u8>, String)> =
            sqlx::query_as("SELECT ciphertext, algorithm FROM secrets WHERE id = $1")
                .bind(handle.id)
                .fetch_optional(&mut *tx)
                .await?;
        tx.commit().await?;

        let Some((ciphertext_bytes, algorithm)) = row else {
            return Err(SecretError::NotFound(handle.id));
        };
        if algorithm != VAULT_ALGORITHM_TAG {
            // Wrong-backend read: a row written by `PgcryptoStore`
            // cannot be decrypted here without re-encryption. Map
            // to Decrypt so the caller surfaces the same shape it
            // would for a tampered ciphertext.
            return Err(SecretError::Decrypt);
        }
        let ciphertext_str =
            std::str::from_utf8(&ciphertext_bytes).map_err(|_| SecretError::Decrypt)?;

        let key_name = vault_key_name(&self.key_prefix, handle.organization_id);
        let plaintext = self.transit.decrypt(&key_name, ciphertext_str).await?;
        Ok(SecretString::from(plaintext))
    }

    async fn delete(&self, handle: &SecretRef) -> Result<(), SecretError> {
        metrics::counter!(SECRET_STORE_DISPATCH_TOTAL, "backend" => "vault", "op" => "delete")
            .increment(1);
        let mut tx = self.pool.begin().await?;
        sqlx::query(&set_local_tenant(handle.organization_id))
            .execute(&mut *tx)
            .await?;
        sqlx::query(
            "UPDATE secrets SET ciphertext = ''::bytea, wrapped_dek = ''::bytea WHERE id = $1",
        )
        .bind(handle.id)
        .execute(&mut *tx)
        .await?;
        sqlx::query("DELETE FROM secrets WHERE id = $1")
            .bind(handle.id)
            .execute(&mut *tx)
            .await?;
        tx.commit().await?;
        Ok(())
    }
}

/// Production [`VaultTransit`] talking to a real `HashiCorp` Vault
/// instance via its HTTP API.
///
/// Three endpoints, all under `/v1/transit/`:
/// - `POST keys/<name>` — create the named key (idempotent on
///   the Vault side; we treat 200 + 204 as success and any 4xx
///   that mentions "exists" as benign).
/// - `POST encrypt/<name>` — body `{"plaintext": "<base64>"}`
///   → response `{"data": {"ciphertext": "vault:vN:..."}}`.
/// - `POST decrypt/<name>` — body `{"ciphertext": "vault:vN:..."}`
///   → response `{"data": {"plaintext": "<base64>"}}`.
///
/// The token is held in a [`SecretString`] for the lifetime of the
/// client; rotation is operator-triggered (an upstream Vault flow
/// re-issues + we restart). Sprint 5+ ticket: rotate without
/// restart by hot-swapping the token via a periodic
/// `tokio::sync::Notify`.
pub struct HttpVaultTransit {
    client: reqwest::Client,
    base_url: url::Url,
    token: SecretString,
}

impl HttpVaultTransit {
    /// Build with an explicit Vault base URL + token. The base URL
    /// must include the scheme (`https://vault.example.com`); the
    /// `/v1/transit/` segments are appended internally.
    ///
    /// # Errors
    /// [`SecretError::InvalidKek`] when the URL doesn't parse or
    /// the reqwest client cannot be built.
    pub fn new(base_url: &str, token: SecretString) -> Result<Self, SecretError> {
        let parsed = url::Url::parse(base_url).map_err(|e| {
            SecretError::InvalidKek(format!("KUBINATE__VAULT_ADDR invalid url: {e}"))
        })?;
        let client = reqwest::Client::builder()
            .timeout(std::time::Duration::from_secs(15))
            .build()
            .map_err(|e| SecretError::InvalidKek(format!("reqwest client: {e}")))?;
        Ok(Self {
            client,
            base_url: parsed,
            token,
        })
    }

    /// Build from `KUBINATE__VAULT_ADDR` + `KUBINATE__VAULT_TOKEN`.
    /// Both env vars are required.
    ///
    /// # Errors
    /// [`SecretError::InvalidKek`] when either var is missing or
    /// malformed.
    pub fn from_env() -> Result<Self, SecretError> {
        let addr = std::env::var("KUBINATE__VAULT_ADDR")
            .map_err(|_| SecretError::InvalidKek("KUBINATE__VAULT_ADDR not set".into()))?;
        let token = std::env::var("KUBINATE__VAULT_TOKEN")
            .map_err(|_| SecretError::InvalidKek("KUBINATE__VAULT_TOKEN not set".into()))?;
        Self::new(&addr, SecretString::from(token))
    }

    fn url_for(&self, segment: &str) -> Result<url::Url, SecretError> {
        let path = format!("v1/transit/{segment}");
        self.base_url
            .join(&path)
            .map_err(|e| SecretError::InvalidKek(format!("vault url join: {e}")))
    }
}

