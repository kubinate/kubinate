/// Map a Vault HTTP status (without the body — bodies are scrubbed
/// before they reach error variants to keep tracing logs from
/// echoing key paths or response fragments) to a `SecretError`.
///
/// - 401 / 403 → `AuthFailed` (rotate the `AppRole` secret-id; check
///   the policy).
/// - 404 → `AuthFailed` ("key not found" — usually means the
///   `AppRole`'s policy doesn't grant create on the key path, or the
///   key was deleted out-of-band).
/// - 400 with the upstream "could not be decrypted" sentinel →
///   `Decrypt` (handled by the caller, which already has the body
///   for that one specific match).
/// - everything else (5xx, transport) → `InvalidKek` ("operational
///   misconfiguration; not auth, not tampered ciphertext").
fn vault_status_to_error(status: reqwest::StatusCode, op: &str) -> SecretError {
    match status.as_u16() {
        401 | 403 | 404 => SecretError::AuthFailed(format!("vault {op} {status}")),
        _ => SecretError::InvalidKek(format!("vault {op} {status}")),
    }
}

#[async_trait]
impl VaultTransit for HttpVaultTransit {
    async fn ensure_key(&self, key_name: &str) -> Result<(), SecretError> {
        let url = self.url_for(&format!("keys/{key_name}"))?;
        let response = self
            .client
            .post(url)
            .header("X-Vault-Token", self.token.expose_secret())
            // Body is required by Vault's transit/keys endpoint;
            // empty JSON is enough since the defaults
            // (`type = "aes256-gcm96"`) suit our use.
            .header("Content-Type", "application/json")
            .body("{}")
            .send()
            .await
            .map_err(|e| {
                tracing::debug!(error = %e, op = "ensure_key", "vault transport");
                SecretError::InvalidKek("vault ensure_key transport".into())
            })?;
        let status = response.status();
        // Vault returns 204 on create + 204 on no-op re-create; both success.
        if status.is_success() {
            return Ok(());
        }
        // Read the body for the "already exists" sentinel (benign)
        // and to log at debug level. Body never reaches the error
        // variant — tracing logs an Vault-error error variant
        // never echoes back a key path or echoed token name.
        let body = response.text().await.unwrap_or_default();
        if body.to_lowercase().contains("already exists") {
            return Ok(());
        }
        tracing::debug!(op = "ensure_key", %status, body, "vault non-success");
        Err(vault_status_to_error(status, "ensure_key"))
    }

    async fn encrypt(&self, key_name: &str, plaintext: &str) -> Result<String, SecretError> {
        use base64::{engine::general_purpose::STANDARD as B64, Engine};
        let url = self.url_for(&format!("encrypt/{key_name}"))?;
        let body = VaultEncryptRequest {
            plaintext: &B64.encode(plaintext.as_bytes()),
        };
        let response = self
            .client
            .post(url)
            .header("X-Vault-Token", self.token.expose_secret())
            .json(&body)
            .send()
            .await
            .map_err(|e| {
                tracing::debug!(error = %e, op = "encrypt", "vault transport");
                SecretError::InvalidKek("vault encrypt transport".into())
            })?;
        let status = response.status();
        if !status.is_success() {
            let body = response.text().await.unwrap_or_default();
            tracing::debug!(op = "encrypt", %status, body, "vault non-success");
            return Err(vault_status_to_error(status, "encrypt"));
        }
        let parsed: VaultEncryptResponse = response.json().await.map_err(|e| {
            tracing::debug!(error = %e, op = "encrypt", "vault json parse");
            SecretError::InvalidKek("vault encrypt response parse".into())
        })?;
        Ok(parsed.data.ciphertext)
    }

    async fn decrypt(&self, key_name: &str, ciphertext: &str) -> Result<String, SecretError> {
        use base64::{engine::general_purpose::STANDARD as B64, Engine};
        let url = self.url_for(&format!("decrypt/{key_name}"))?;
        let body = VaultDecryptRequest { ciphertext };
        let response = self
            .client
            .post(url)
            .header("X-Vault-Token", self.token.expose_secret())
            .json(&body)
            .send()
            .await
            .map_err(|e| {
                tracing::debug!(error = %e, op = "decrypt", "vault transport");
                SecretError::InvalidKek("vault decrypt transport".into())
            })?;
        let status = response.status();
        if !status.is_success() {
            let body = response.text().await.unwrap_or_default();
            tracing::debug!(op = "decrypt", %status, body, "vault non-success");
            // Vault returns 400 with body containing "ciphertext
            // could not be decrypted" for tampered ciphertext.
            // Match that specific case before the generic mapping.
            if body.to_lowercase().contains("could not be decrypted") {
                return Err(SecretError::Decrypt);
            }
            return Err(vault_status_to_error(status, "decrypt"));
        }
        let parsed: VaultDecryptResponse =
            response.json().await.map_err(|_| SecretError::Decrypt)?;
        let plaintext_bytes = B64
            .decode(parsed.data.plaintext.as_bytes())
            .map_err(|_| SecretError::Decrypt)?;
        String::from_utf8(plaintext_bytes).map_err(|_| SecretError::Decrypt)
    }
}

#[cfg(test)]
